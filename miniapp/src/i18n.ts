export type TranslationKey = keyof typeof catalog
export const translationKeys = Object.keys(catalog) as TranslationKey[]

const indexes: Record<Language, number> = {
  'zh-CN': 0,
  'zh-TW': 1,
  en: 2,
  'cat-cute': 3,
  'cat-cold': 4,
}

export const supportedLanguages: Array<{ id: Language; nameKey: TranslationKey }> = [
  { id: 'zh-CN', nameKey: 'languageZhCn' },
  { id: 'zh-TW', nameKey: 'languageZhTw' },
  { id: 'en', nameKey: 'languageEn' },
  { id: 'cat-cute', nameKey: 'languageCatCute' },
  { id: 'cat-cold', nameKey: 'languageCatCold' },
]

export function normalizeLanguage(value: unknown): Language {
  const key = String(value || '') as Language
  return key in indexes ? key : 'zh-CN'
}

export function readLanguage(): Language {
  try {
    return normalizeLanguage(wx?.getStorageSync?.(LANGUAGE_KEY))
  } catch {
    return 'zh-CN'
  }
}

export function translate(
  key: TranslationKey,
  params: Params = {},
  language: Language = readLanguage(),
): string {
  const template = catalog[key][indexes[language]] || catalog[key][0]
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ))
}

export function localeFor(language: Language): string {
  if (language === 'en') return 'en-US'
  if (language === 'zh-TW') return 'zh-TW'
  return 'zh-CN'
}
