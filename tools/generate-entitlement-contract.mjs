import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTRACT_PATH = resolve(ROOT, 'contracts/entitlements.v1.json');
const NODE_PATH = resolve(ROOT, 'auth/generated/entitlements.js');
const PYTHON_PATH = resolve(ROOT, 'agents/_domain/entitlements/generated_contract.py');
const EXPECTED_PLANS = Object.freeze(['guest', 'free', 'plus', 'pro']);
const EXPECTED_AUTH_TYPES = Object.freeze(['guest', 'wechat', 'cloudbase']);
const LIMIT_KEYS = Object.freeze([
  'search_depth',
  'concurrent_runs',
  'daily_tokens',
  'user_skill_uploads',
]);

function fail(message) {
  throw new Error(`Invalid entitlement contract: ${message}`);
}

function validateContract(contract) {
  const topKeys = Object.keys(contract).sort();
  const expectedTopKeys = [
    'auth_types',
    'guest_skill_ids',
    'limits',
    'payment_available',
    'plans',
    'version',
  ];
  if (JSON.stringify(topKeys) !== JSON.stringify(expectedTopKeys)) {
    fail(`unexpected top-level keys: ${topKeys.join(', ')}`);
  }
  if (contract.version !== 1) fail('version must be 1');
  if (JSON.stringify(contract.plans) !== JSON.stringify(EXPECTED_PLANS)) {
    fail('plans must preserve guest, free, plus, pro order');
  }
  if (JSON.stringify(contract.auth_types) !== JSON.stringify(EXPECTED_AUTH_TYPES)) {
    fail('auth_types must preserve guest, wechat, cloudbase order');
  }
  if (
    !Array.isArray(contract.guest_skill_ids)
    || contract.guest_skill_ids.some((value) => typeof value !== 'string' || !value)
    || new Set(contract.guest_skill_ids).size !== contract.guest_skill_ids.length
  ) {
    fail('guest_skill_ids must contain unique non-empty strings');
  }
  if (typeof contract.payment_available !== 'boolean') {
    fail('payment_available must be boolean');
  }
  if (
    !contract.limits
    || JSON.stringify(Object.keys(contract.limits)) !== JSON.stringify(EXPECTED_PLANS)
  ) {
    fail('limits must define the four plans in contract order');
  }
  for (const plan of EXPECTED_PLANS) {
    const limits = contract.limits[plan];
    if (
      !limits
      || JSON.stringify(Object.keys(limits).sort()) !== JSON.stringify([...LIMIT_KEYS].sort())
    ) {
      fail(`${plan} limits have unexpected keys`);
    }
    if (!['basic', 'standard', 'deep'].includes(limits.search_depth)) {
      fail(`${plan}.search_depth is invalid`);
    }
    for (const key of LIMIT_KEYS.slice(1)) {
      if (!Number.isInteger(limits[key]) || limits[key] < 0) {
        fail(`${plan}.${key} must be a non-negative integer`);
      }
    }
  }
}

function jsLiteral(value) {
  return JSON.stringify(value, null, 2);
}

function renderNode(contract) {
  const camelLimits = Object.fromEntries(contract.plans.map((plan) => [
    plan,
    {
      searchDepth: contract.limits[plan].search_depth,
      concurrentRuns: contract.limits[plan].concurrent_runs,
      dailyTokens: contract.limits[plan].daily_tokens,
      userSkillUploads: contract.limits[plan].user_skill_uploads,
    },
  ]));
  return `// Generated by tools/generate-entitlement-contract.mjs. Do not edit.

function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const item of Object.values(value)) deepFreeze(item);
    Object.freeze(value);
  }
  return value;
}

export const ENTITLEMENT_CONTRACT = deepFreeze(${jsLiteral(contract)});
export const AUTH_TYPES = ENTITLEMENT_CONTRACT.auth_types;
export const MEMBERSHIP_PLANS = ENTITLEMENT_CONTRACT.plans;
export const PLAN_LIMITS = deepFreeze(${jsLiteral(camelLimits)});
export const GUEST_SKILL_IDS = ENTITLEMENT_CONTRACT.guest_skill_ids;
export const PAYMENT_AVAILABLE = ENTITLEMENT_CONTRACT.payment_available;
`;
}

function pythonLiteral(value, indent = 0, arraysAsTuples = true) {
  if (value === null) return 'None';
  if (value === true) return 'True';
  if (value === false) return 'False';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) {
    const items = value.map((item) => pythonLiteral(item, indent, arraysAsTuples)).join(', ');
    if (!arraysAsTuples) return `[${items}]`;
    return `(${items}${value.length === 1 ? ',' : ''})`;
  }
  const padding = ' '.repeat(indent);
  const childPadding = ' '.repeat(indent + 4);
  const entries = Object.entries(value).map(
    ([key, item]) => `${childPadding}${JSON.stringify(key)}: ${pythonLiteral(item, indent + 4, arraysAsTuples)},`,
  );
  return `{\n${entries.join('\n')}\n${padding}}`;
}

function renderPython(contract) {
  return `"""Generated entitlement contract. Do not edit by hand."""

from __future__ import annotations

from typing import Final


ENTITLEMENT_VERSION: Final = ${contract.version}
AUTH_TYPES: Final = ${pythonLiteral(contract.auth_types)}
MEMBERSHIP_PLANS: Final = ${pythonLiteral(contract.plans)}
GUEST_SKILL_IDS: Final = frozenset(${pythonLiteral(contract.guest_skill_ids)})
PLAN_LIMITS: Final = ${pythonLiteral(contract.limits)}
PAYMENT_AVAILABLE: Final = ${pythonLiteral(contract.payment_available)}
ENTITLEMENT_CONTRACT: Final = ${pythonLiteral(contract, 0, false)}
`;
}

async function verifyOrWrite(path, content, check) {
  let existing = '';
  try {
    existing = await readFile(path, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (existing === content) return;
  if (check) throw new Error(`Generated entitlement module is stale: ${path}`);
  await writeFile(path, content, 'utf8');
}

const contract = JSON.parse(await readFile(CONTRACT_PATH, 'utf8'));
validateContract(contract);
const check = process.argv.includes('--check');
await Promise.all([
  verifyOrWrite(NODE_PATH, renderNode(contract), check),
  verifyOrWrite(PYTHON_PATH, renderPython(contract), check),
]);
if (check) {
  process.stdout.write('Entitlement generated modules are current.\n');
}
